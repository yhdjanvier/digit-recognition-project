"""Evaluate Document mode (pretrained OCR) on pages that have ground-truth text.

Usage: python evaluate_ocr.py [folder]        (default: tests/ocr_samples)
For every <name>.png/.jpg/.pdf with a matching <name>.txt it computes CER and WER
and writes results/ocr_evaluation.json and results/ocr_evaluation.md.
"""
import sys
import time
from pathlib import Path

import config as C
from src.document_ocr import pages_to_text, read_document
from src.ocr_metrics import cer, wer
from src.utils import save_json

EXTS = {".png", ".jpg", ".jpeg", ".pdf"}


def main(folder: Path) -> int:
    files = sorted(p for p in folder.iterdir() if p.suffix.lower() in EXTS and p.with_suffix(".txt").exists())
    if not files:
        print(f"No image + .txt pairs found in {folder}. Run `python make_ocr_samples.py` first.")
        return 1
    rows = []
    for p in files:
        truth = p.with_suffix(".txt").read_text(encoding="utf-8")
        t0 = time.time()
        text = pages_to_text(read_document(p.read_bytes(), p.name))
        rows.append({"file": p.name, "cer": cer(truth, text), "wer": wer(truth, text),
                     "seconds": round(time.time() - t0, 1), "recognised": text})
        print(f"{p.name:32s} CER {rows[-1]['cer']:.3f}  WER {rows[-1]['wer']:.3f}  ({rows[-1]['seconds']} s)")
    mean_cer = sum(r["cer"] for r in rows) / len(rows)
    mean_wer = sum(r["wer"] for r in rows) / len(rows)
    print(f"\nMEAN  CER {mean_cer:.3f}  WER {mean_wer:.3f}   (0 = perfect, lower is better)")
    save_json({"mean_cer": mean_cer, "mean_wer": mean_wer, "pages": rows,
               "engine": "EasyOCR (pretrained)"}, C.RESULTS_DIR / "ocr_evaluation.json")
    md = ["# Document-mode OCR evaluation (generated by evaluate_ocr.py)", "",
          "| File | CER | WER | Seconds |", "|---|---|---|---|"]
    md += [f"| {r['file']} | {r['cer']:.3f} | {r['wer']:.3f} | {r['seconds']} |" for r in rows]
    md += ["", f"**Mean CER {mean_cer:.3f} - mean WER {mean_wer:.3f}**"]
    (C.RESULTS_DIR / "ocr_evaluation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]) if len(sys.argv) > 1 else C.ROOT_DIR / "tests" / "ocr_samples"))
